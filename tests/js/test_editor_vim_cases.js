// Key sequences checked against real Vim 9.2 (vim -Nu NONE with ai et sw=2 nojs so=0).
// Each row: start text, keys, expected text; "|" marks the cursor.
// Left out on purpose: undo after several commands (Vim's scripted input does not split undo
// steps, so it cannot check them; test_editor_engine.js covers undo), Vim regex syntax
// (patterns here are JavaScript regexes), octal numbers, and "ß" upper-casing.
import { assertEqual, test } from "./harness.js";
import { run } from "./editor-helpers.js";

function table(group, rows) {
  for (const [start, keys, expected] of rows) {
    test(`vim ${group}: ${keys} on ${JSON.stringify(start)}`, () => {
      assertEqual(run(start, keys), expected);
    });
  }
}

